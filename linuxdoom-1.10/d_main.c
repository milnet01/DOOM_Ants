extern  boolean         demorecording;

// DOOM-0203: >0 when the headless CI boot-smoke (`-bootsmoke [N]`) is armed; the
// number of game tics to simulate before exiting 0. Set in D_DoomMain.
static int              bootsmoke_tics = 0;

void D_DoomLoop (void)
{
    if (demorecording)
	G_BeginRecording ();
		
    if (M_CheckParm ("-debugfile"))
    {
	char    filename[20];
	sprintf (filename,"debug%i.txt",consoleplayer);
	printf ("debug output to: %s\n",filename);
	debugfile = fopen (filename,"w");
    }
	
    I_InitGraphics ();

    // DOOM-0203: the headless CI boot-smoke runs on a GPU-less runner. Pin the
    // software renderer so a stray software Vulkan ICD (e.g. lavapipe) can't pull
    // us onto the GPU path that has no device to render on.
    if (bootsmoke_tics > 0)
	rendermode = RB_CLASSIC;

    // Pick + init the renderer back-end now the SDL/graphics device exists,
    // so a back-end's Available()/Init() can probe the GPU (DOOM-0026).
    RB_Init ();

    int bootsmokeStart = gametic;   // DOOM-0203: baseline for the tic countdown

    while (1)
    {
	// frame syncronous IO operations
	I_StartFrame ();

	// DOOM-0048: in single-player 3D, decouple the present rate from the 35 Hz
	// game tic. Run every tic that is due without blocking, then render an
	// interpolated in-between frame paced by vsync, so the camera is smooth above
	// 35 FPS while the simulation stays locked to 35 Hz. Net/demo/Classic keep the
	// classic tic-locked path (sync + demo determinism + no wasted software redraws).
	static boolean wasUncapped = false;
	static int     lastTicMs   = 0;
	boolean uncapped = !singletics && !netgame && !demoplayback
			 && !demorecording && rendermode != RB_CLASSIC;
	int ticBefore = gametic;

	// process one or more tics
	if (singletics)
	{
	    I_StartTic ();
	    D_ProcessEvents ();
	    G_BuildTiccmd (&netcmds[consoleplayer][maketic%BACKUPTICS]);
	    if (advancedemo)
		D_DoAdvanceDemo ();
	    M_Ticker ();
	    G_Ticker ();
	    gametic++;
	    maketic++;
	}
	else if (uncapped)
	{
	    // Non-blocking equivalent of TryRunTics for one node: NetUpdate() reads
	    // input and advances maketic at 35 Hz; run each available tic, capped at
	    // a second so a long stall can't spiral.
	    int guard = 0;
	    NetUpdate ();
	    while (gametic < maketic && guard++ < TICRATE)
	    {
		if (advancedemo)
		    D_DoAdvanceDemo ();
		M_Ticker ();
		G_Ticker ();
		gametic++;
	    }
	}
	else
	{
	    TryRunTics (); // will run at least one tic
	}

	// Drive the render interpolation (DOOM-0048). Reset on entry so a stale frame
	// can't smear; snapshot when a tic ran; set the sub-tic fraction every frame.
	if (uncapped)
	{
	    player_t* vp = &players[consoleplayer];
	    if (!wasUncapped)
		RB_InterpReset (vp);
	    if (gametic != ticBefore)
	    {
		RB_InterpSnapshot (vp);
		lastTicMs = I_GetTimeMS ();
	    }
	    RB_InterpSetFrac ((double)(I_GetTimeMS () - lastTicMs) / (1000.0 / TICRATE));
	}
	else
	{
	    RB_InterpDisable ();
	}
	wasUncapped = uncapped;

	S_UpdateSounds (players[consoleplayer].mo);// move positional sounds

	// Update display, next frame, with current state.
	D_Display ();

	// DOOM-0203: headless boot-smoke — once N tics have simulated (world stepped
	// + software renderer drew each frame without crashing), the engine has proven
	// it boots and renders; exit cleanly (0). Unlike -timedemo, no demo lump and
	// no I_Error timing report, so a passing run is exit 0.
	if (bootsmoke_tics > 0 && gametic - bootsmokeStart >= bootsmoke_tics)
	{
	    printf ("bootsmoke: %d tics simulated OK, exiting.\n",
		    gametic - bootsmokeStart);
	    I_Quit ();
	}

#ifndef SNDSERV
	// Sound mixing for the buffer is snychronous.
	I_UpdateSound();
#endif	
	// Synchronous sound output is explicitly called.
#ifndef SNDINTR
	// Update sound output.
	I_SubmitSound();
#endif
    }
}



